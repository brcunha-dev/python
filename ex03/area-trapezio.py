print("Vamos calcular a área de um trapézio!")

# Declaração de variaveis
baseMaior = float(input("Digite o valor da base maior: "))
baseMenor = float(input("Digite o valor da base menor: "))
altura = float(input("Digite o valor da altura: "))
area = (baseMaior+baseMenor)/2*altura

print(f"A área do trapézio informado é de: {area}")